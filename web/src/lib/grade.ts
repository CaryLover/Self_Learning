/** 当前年级与"防超纲"约束文案（喂给模型，避免用高年级方法讲解） */

import type { Grade } from "./types";

export const GRADE_LEVELS: Record<Grade, string[]> = {
  primary: ["一年级", "二年级", "三年级", "四年级", "五年级", "六年级"],
  junior: ["初一", "初二", "初三"],
  senior: ["高一", "高二", "高三"],
};

export const GRADE_NAME: Record<Grade, string> = {
  primary: "小学",
  junior: "初中",
  senior: "高中",
};

/** 学段下是否包含该年级 */
export function isValidLevel(grade: Grade, level?: string): boolean {
  return !!level && GRADE_LEVELS[grade].includes(level);
}

/**
 * 生成"年级约束"文本：约束讲解方法、题目难度与解题工具，
 * 明确禁止超纲（例如小学阶段用方程解鸡兔同笼）。
 */
export function curriculumRule(grade: Grade, gradeLevel?: string): string {
  const level = isValidLevel(grade, gradeLevel) ? gradeLevel : undefined;
  const who = level || GRADE_NAME[grade];

  if (grade === "primary") {
    const early = ["一年级", "二年级", "三年级"].includes(level || "");
    return `【年级约束 · 最高优先级，防止超纲】
- 学生当前年级：${who}（${level ? `小学${early ? "低中段" : "中高段"}` : "小学"}）。
- 只能使用该年级及以下**已经学过**的知识与方法进行讲解、提问和出题。
- 数学应用题不使用初中代数方法解题：不设未知数 x、不列初中方程、不移项、不消元——即使这些方法更快也不行。
  · 典型例子：鸡兔同笼必须用画图、列表枚举、假设法（"假设全是鸡，那么腿一共有……"）等小学方法；不得写 x + y = 7 之类的方程。
- 不使用函数、负数运算、字母代数式、根号、比例式（该年级未学时）；不用初中的几何证明格式。
- ${early ? "计算尽量限在整数与已学过的运算范围内，步骤不跳步。" : "步骤要能在纸上一目了然，不跳步；尽量保持整数运算。"}
- 如果孩子的问题确实超出该年级：改用更简单的同类问题，或先补必要的前置知识，并明确告诉孩子"要先学会 X 才能做这道题"。`;
  }

  if (grade === "junior") {
    return `【年级约束 · 最高优先级，防止超纲】
- 学生当前年级：${who}（初中）。
- 数学相关题目可以使用该年级已经学过的方程、不等式、函数、几何和统计知识；二次函数属于义务教育内容，但必须考虑学生当前年级和实际学习进度。
- 不得使用超出义务教育阶段的高中方法，例如数列求和、导数、排列组合与二项式定理；不确定学生是否学过某个方法时，优先解释前置知识或采用更直观的方式。
- 应用题优先按该年级教材的通行解法；若使用方程，先说明"设……为 x"以及为什么可以这样设，并检查解是否符合实际意义（人数、长度不能为负等）。
- 几何题不得直接引用未学的定理；需要用到的定理先说明名称与成立条件。`;
  }

  return `【年级约束 · 最高优先级，防止超纲】
- 学生当前年级：${who}（高中）。
- 可使用高中课程标准内的方法：函数与导数、数列、三角、向量、立体几何、解析几何、概率统计。
- 不得使用大学内容（极限的 ε-δ 定义、中值定理、线性代数、概率测度、复变函数等）。
- 培优题可到高考压轴难度，但必须给出可检验的推理链，不得跳步。`;
}
