export function stickerFor(seed: number): string {
  return STICKERS[Math.abs(seed) % STICKERS.length]!;
}

export function dailyTip(): string {
  const day = Math.floor(Date.now() / 86_400_000);
  return TIPS[day % TIPS.length]!;
}
