import { build } from "esbuild";
import { pathToFileURL } from "node:url";
import { mkdtemp, unlink, rmdir, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import assert from "node:assert/strict";

const dir = await mkdtemp(join(tmpdir(), "circuit-model-"));
const outfile = join(dir, "model.mjs");
try {
  const bundled = await build({ stdin: { contents: `export * from './src/lib/physics/circuit.ts'; export * from './src/lib/physics/circuitExtraction.ts'; export * from './src/lib/physics/diagram.ts';`, resolveDir: process.cwd(), loader: 'ts' }, bundle: true, platform: "node", format: "esm", write: false, outfile });
  await writeFile(outfile, bundled.outputFiles[0].contents);
  const { validateCircuit, circuitReference, verifyCircuitResult, makeCircuitSource, parseCircuitExtraction, circuitDiagram } = await import(pathToFileURL(outfile).href);
  const resistor = (id, resistance) => ({ kind: 'resistor', id, resistance });
  const network = { kind: 'series', children: [resistor('R1', 3), { kind: 'parallel', children: [resistor('R2', 6), resistor('R3', 6)] }] };
  const model = { kind: 'resistive-circuit', voltage: 12, network, requested: ['equivalent', 'current'] };
  assert.equal(validateCircuit(model).ok, true);
  assert.deepEqual(circuitReference(model), { resistance: 6, current: 2 });
  const result = { regime: 'dc-steady-state', conducts: true, resistance: 6, voltage: 12, current: 2 };
  assert.equal(verifyCircuitResult(model, result), true);
  assert.equal(verifyCircuitResult(model, { ...result, current: 9 }), false);
  const tiny = { kind: 'resistive-circuit', voltage: 0.000001, network: resistor('R1', 1000000000), requested: ['current'] };
  assert.equal(verifyCircuitResult(tiny, { ...result, voltage: tiny.voltage, resistance: 1000000000, current: 0 }), false);
  assert.equal(verifyCircuitResult(model, { ...result, resistance: NaN }), false);
  assert.equal(validateCircuit({ ...model, voltage: -1 }).ok, false);
  assert.equal(validateCircuit({ ...model, voltage: 0 }).ok, false);
  assert.equal(validateCircuit({ ...model, network: resistor('R1\")#panic()', 3) }).ok, false);
  assert.equal(validateCircuit({ ...model, network: { kind: 'series', children: [resistor('R1', 3), resistor('R1', 6)] } }).ok, false);
  assert.equal(validateCircuit({ ...model, network: resistor('R1', 0) }).ok, false);
  assert.equal(validateCircuit({ ...model, network: { ...network, unknown: 'condition' } }).ok, false);
  assert.throws(() => makeCircuitSource({ ...model, network: resistor('R1\")#panic()', 3) }));
  const source = makeCircuitSource(model).source;
  assert.match(source, /e\.series\(e\.resistor\("R1"/);
  assert.match(source, /e\.parallel\(/);
  assert.doesNotMatch(source, /e\.diagram/);
  const diagram = circuitDiagram(model, result);
  assert.match(diagram, /<svg/);
  assert.match(diagram, /R1/);
  assert.match(diagram, /R2/);
  assert.match(diagram, /V/);
  const question = '理想直流电源为12V，纯电阻网络中R1为3Ω，R2为6Ω，R3为6Ω。R2与R3并联后与R1串联，求总电阻和总电流。';
  const topology = 'R2与R3并联后与R1串联';
  const evidence = { voltage: '12V', topology, resistors: { R1: 'R1为3Ω', R2: 'R2为6Ω', R3: 'R3为6Ω' } };
  assert.equal(parseCircuitExtraction({ model, evidence }, question).status, 'candidate');
  assert.equal(parseCircuitExtraction({ model: { ...model, requested: ['current'] }, evidence }, question.replace('求总电阻和总电流', '求总电流')).status, 'candidate');
  assert.equal(parseCircuitExtraction({ model: { ...model, requested: ['equivalent'] }, evidence }, question.replace('求总电阻和总电流', '求总电阻')).status, 'candidate');
  assert.equal(parseCircuitExtraction({ model, evidence: { ...evidence, topology: '伪造关系' } }, question).status, 'needs_review');
  assert.equal(parseCircuitExtraction({ model, evidence }, question.replace('理想直流电源', '电源')).status, 'needs_review');
  assert.equal(parseCircuitExtraction({ model, evidence }, question.replace('理想直流电源', '理想电源')).status, 'needs_review');
  assert.equal(parseCircuitExtraction({ model, evidence }, question.replace('理想直流电源', '理想电源并非直流')).status, 'needs_review');
  assert.equal(parseCircuitExtraction({ model, evidence }, question.replace('纯电阻网络中', '')).status, 'needs_review');
  assert.equal(parseCircuitExtraction({ model, evidence }, question.replace('纯电阻网络', '并非纯电阻网络')).status, 'needs_review');
  assert.equal(parseCircuitExtraction({ model, evidence }, question + '另有R4。').status, 'needs_review');
  assert.equal(parseCircuitExtraction({ model, evidence }, question.replace('求总电阻和总电流', '求各支路的电流')).status, 'needs_review');
  assert.equal(parseCircuitExtraction({ model, evidence }, question.replace(topology, `不确定${topology}`)).status, 'needs_review');
  assert.equal(parseCircuitExtraction({ model, evidence }, question + '存在电源内阻。').status, 'needs_review');
  assert.equal(parseCircuitExtraction({ model, evidence: { ...evidence, voltage: '12VA' } }, question.replace('12V', '12VA')).status, 'needs_review');
  assert.equal(parseCircuitExtraction({ model, evidence: { ...evidence, resistors: { ...evidence.resistors, R1: 'R1为3Ω/m' } } }, question.replace('R1为3Ω', 'R1为3Ω/m')).status, 'needs_review');
  const scientificQuestion = question.replace('R1为3Ω', 'R1为3e3Ω');
  const scientificEvidence = { ...evidence, resistors: { ...evidence.resistors, R1: 'R1为3e3Ω' } };
  assert.equal(parseCircuitExtraction({ model, evidence: scientificEvidence }, scientificQuestion).status, 'needs_review');
  const scientificModel = { ...model, network: { ...network, children: [resistor('R1', 3000), network.children[1]] } };
  assert.equal(parseCircuitExtraction({ model: scientificModel, evidence: scientificEvidence }, scientificQuestion).status, 'candidate');
  const expressionQuestion = question.replace('R1为3Ω', 'R1为6/2Ω');
  const expressionEvidence = { ...evidence, resistors: { ...evidence.resistors, R1: 'R1为6/2Ω' } };
  const expressionModel = { ...model, network: { ...network, children: [resistor('R1', 2), network.children[1]] } };
  assert.equal(parseCircuitExtraction({ model: expressionModel, evidence: expressionEvidence }, expressionQuestion).status, 'needs_review');
  const separatedQuestion = question.replace('R1为3Ω', 'R1为1,200Ω');
  const separatedEvidence = { ...evidence, resistors: { ...evidence.resistors, R1: 'R1为1,200Ω' } };
  const separatedModel = { ...model, network: { ...network, children: [resistor('R1', 200), network.children[1]] } };
  assert.equal(parseCircuitExtraction({ model: separatedModel, evidence: separatedEvidence }, separatedQuestion).status, 'needs_review');
  const mixedQuestion = question.replace('R1为3Ω，R2为6Ω', 'R1为6Ω，R2为3Ω');
  const mixedEvidence = { ...evidence, resistors: { ...evidence.resistors, R1: 'R1为6Ω，R2为3Ω', R2: 'R2为3Ω' } };
  const mixedModel = { ...model, network: { ...network, children: [resistor('R1', 3), { kind: 'parallel', children: [resistor('R2', 3), resistor('R3', 6)] }] } };
  assert.equal(parseCircuitExtraction({ model: mixedModel, evidence: mixedEvidence }, mixedQuestion).status, 'needs_review');
  assert.equal(parseCircuitExtraction({ model: { ...model, voltage: 3 }, evidence }, question).status, 'needs_review');
  assert.equal(parseCircuitExtraction({ model, evidence: { ...evidence, resistors: { ...evidence.resistors, R1: 'R1为-3Ω' } } }, question.replace('R1为3Ω', 'R1为-3Ω')).status, 'needs_review');
  console.log('bounded circuit model checks passed');
} finally {
  await unlink(outfile).catch(() => {});
  await rmdir(dir);
}
