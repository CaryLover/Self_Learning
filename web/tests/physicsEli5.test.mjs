import { build } from "esbuild";
import { pathToFileURL } from "node:url";
import { mkdtemp, unlink, rmdir, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import assert from "node:assert/strict";

const dir = await mkdtemp(join(tmpdir(), "physics-eli5-"));
const outfile = join(dir, "fusion.mjs");
try {
  const bundle = await build({ stdin: { contents: `export { addEli5PhysicsExplanation, restorePhysicsCandidate, finishPhysicsWithoutExplanation } from './src/lib/physics/eli5Explain.ts'; export { recoverSession } from './src/lib/recoverSession.ts'; export { composeInclineLesson } from './src/lib/physics/composeLesson.ts'; export { buildInclinePractices } from './src/lib/physics/practice.ts';`, resolveDir: process.cwd(), loader: 'ts' }, bundle: true, platform: "node", format: "esm", write: false, outfile });
  await writeFile(outfile, bundle.outputFiles[0].contents);
  const { addEli5PhysicsExplanation, restorePhysicsCandidate, finishPhysicsWithoutExplanation, recoverSession, composeInclineLesson, buildInclinePractices } = await import(pathToFileURL(outfile).href);
  const model = { kind: 'smooth-incline', objectName: 'A', massKg: { value: 2, source: 'stated' }, angleDeg: { value: 30, source: 'stated' }, gravity: { value: 10, source: 'stated' }, surface: { value: 'fixed-smooth', source: 'stated' }, extraForces: { value: 'none', source: 'stated' }, requested: ['forces', 'normal', 'acceleration'] };
  const physicalResult = { status: 'solved', model: 'single-contact-body', normal: 20 * Math.cos(Math.PI / 6), acceleration: 5, forces: [{ role: 'weight', direction: [0, -1] }, { role: 'normal', direction: [-0.5, Math.cos(Math.PI / 6)] }] };
  const fixed = composeInclineLesson(model, physicalResult, '<svg><path d="M1 2"/></svg>');
  const candidate = { status: 'candidate', html: fixed, model, result: physicalResult, assumptions: [], evidence: {}, practices: buildInclinePractices(model, physicalResult) };
  const modelReply = JSON.stringify({ status: 'ok', intro: '先观察研究对象。', steps: ['找到重力方向。', '再看斜面的支持力。'], summary: '<script>坏内容</script>' });
  let captured;
  const options = { candidate, topic: '物块在光滑斜面上', grade: 'senior', ctx: {}, signal: new AbortController().signal, call: async messages => { captured = messages; return modelReply; } };
  const result = await addEli5PhysicsExplanation(options);
  assert.match(captured[0].content, /第一次接触/);
  assert.match(captured[0].content, /不能修改或省略条件/);
  assert.ok(!captured[1].content.includes('<svg'));
  assert.match(captured[1].content, /17\.32/);
  assert.ok(result.html.includes('<svg><path d="M1 2"/></svg>'));
  assert.ok(result.html.includes('17.32 N'));
  assert.ok(result.html.includes('先观察研究对象。'));
  assert.ok(result.html.includes('&lt;script&gt;坏内容&lt;/script&gt;'));
  assert.ok(!result.html.includes('<script>'));
  assert.deepEqual(result.practices, candidate.practices);
  const saved = JSON.parse(JSON.stringify({ stage: 'error', html: candidate.html, retryPhysicsExplanation: true, pendingPhysicsPractices: candidate.practices, physicsPreview: { status: 'candidate', modelVersion: 'typed-physics:0.3.0', model: candidate.model, result: candidate.result, evidence: candidate.evidence, assumptions: candidate.assumptions } }));
  const restored = restorePhysicsCandidate(saved);
  assert.deepEqual(restored, candidate);
  const skipped = finishPhysicsWithoutExplanation(saved);
  assert.equal(skipped.stage, 'done');
  assert.equal(skipped.html, candidate.html);
  assert.deepEqual(skipped.practices, candidate.practices);
  assert.equal(skipped.pendingPhysicsPractices, undefined);
  assert.equal(skipped.retryPhysicsExplanation, false);
  assert.match(skipped.html, /17\.32 N/);
  assert.equal(finishPhysicsWithoutExplanation({ ...saved, retryPhysicsExplanation: false }), null);
  assert.equal(finishPhysicsWithoutExplanation({ ...saved, html: result.html }), null);
  assert.equal(finishPhysicsWithoutExplanation({ ...saved, pendingPhysicsPractices: undefined }), null);
  const retried = await addEli5PhysicsExplanation({ ...options, candidate: restored });
  assert.ok(retried.html.includes('先观察研究对象。'));
  const reopened = recoverSession(JSON.parse(JSON.stringify({ id: 'lesson', eli5: { ...saved, stage: 'physics_explaining', topic: options.topic, retryPhysicsExplanation: false } })));
  const resumed = restorePhysicsCandidate(reopened.eli5);
  assert.deepEqual(resumed, candidate);
  assert.ok((await addEli5PhysicsExplanation({ ...options, candidate: resumed })).html.includes('先观察研究对象。'));
  assert.equal(restorePhysicsCandidate({ ...saved, pendingPhysicsPractices: undefined }), null);
  assert.equal(restorePhysicsCandidate({ ...saved, html: result.html }), null);
  assert.equal(restorePhysicsCandidate({ ...saved, physicsPreview: { ...saved.physicsPreview, result: { ...physicalResult, normal: 99 } } }), null);
  assert.equal(restorePhysicsCandidate({ ...saved, physicsPreview: { ...saved.physicsPreview, modelVersion: 'unknown' } }), null);
  assert.equal(restorePhysicsCandidate({ ...saved, html: saved.html.replace('17.32 N', '99 N') }), null);
  assert.deepEqual(restorePhysicsCandidate({ ...saved, pendingPhysicsPractices: [{ question: '错误练习' }] }).practices, candidate.practices);
  let retries = 0;
  const repaired = await addEli5PhysicsExplanation({ ...options, call: async () => ++retries === 1 ? '不符合格式' : modelReply });
  assert.equal(retries, 2);
  assert.ok(repaired.html.includes('先观察研究对象。'));
  let reviewCalls = 0;
  await assert.rejects(addEli5PhysicsExplanation({ ...options, call: async () => { reviewCalls++; return JSON.stringify({ status: 'needs_review' }); } }));
  assert.equal(reviewCalls, 1);
  await assert.rejects(addEli5PhysicsExplanation({ ...options, call: async () => JSON.stringify({ status: 'ok', intro: '力是 99 N', steps: ['一步', '另一步'], summary: '完成' }) }));
  await assert.rejects(addEli5PhysicsExplanation({ ...options, call: async () => modelReply, candidate: { ...candidate, html: '<main>不完整' } }));
  const controller = new AbortController();
  controller.abort();
  await assert.rejects(addEli5PhysicsExplanation({ ...options, signal: controller.signal, call: async () => { throw new Error('不应调用'); } }));
  const duringCall = new AbortController();
  await assert.rejects(addEli5PhysicsExplanation({ ...options, signal: duringCall.signal, call: async () => { duringCall.abort(); return modelReply; } }));
  console.log('physics and ELI5 integration checks passed');
} finally {
  await unlink(outfile).catch(() => {});
  await rmdir(dir);
}
