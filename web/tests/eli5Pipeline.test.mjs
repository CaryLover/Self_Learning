import { build } from "esbuild";
import { pathToFileURL } from "node:url";
import { mkdtemp, unlink, rmdir, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import assert from "node:assert/strict";

const dir = await mkdtemp(join(tmpdir(), "eli5-test-"));
try {
  const outfile = join(dir, "pipeline.mjs");
  const bundled = await build({ stdin: { contents: `export * from './src/lib/eli5Pipeline.ts'; export { buildEli5ExplainMessages, buildEli5PracticeMessages } from './src/prompts/eli5.ts';`, resolveDir: process.cwd(), loader: "ts" }, bundle: true, platform: "node", format: "esm", write: false, outfile, loader: { ".css": "empty" } });
  await writeFile(outfile, bundled.outputFiles[0].contents);
  const { checkEli5Html, runEli5Pipeline, runEli5Practice, runEli5UnverifiedFallback, buildEli5ExplainMessages, buildEli5PracticeMessages } = await import(pathToFileURL(outfile).href);
  const explainPrompt = buildEli5ExplainMessages('junior', '光合作用', {}, {});
  assert.match(explainPrompt[0].content, /图形形式要服从学科/);
  assert.match(explainPrompt[0].content, /时间轴/);
  const practicePrompt = buildEli5PracticeMessages('junior', '光合作用', '植物利用光能', {}, {});
  assert.match(practicePrompt[0].content, /题目类型要服从学科/);
  assert.match(practicePrompt[0].content, /理科可为压轴题/);
  assert.match(buildEli5ExplainMessages('senior', '函数', {}, {})[0].content, /高考较高难度/);
  const valid = '<!DOCTYPE html><html><head></head><body><p>这是一幅图</p><svg viewBox="0 0 10 10"><circle cx="5" cy="5" r="4"/></svg></body></html>';
  assert.equal(checkEli5Html(valid), null);
  assert.match(checkEli5Html(valid.replace('</body>', `${'x'.repeat(500_001)}</body>`)), /内容过长/);
  assert.equal(checkEli5Html(valid.replace('<svg ', '<svg style="fill:url(#gradient)" ')), null);
  assert.equal(checkEli5Html(valid.replace('<svg ', '<svg style="fill:url(\'#gradient\')" ')), null);
  assert.ok(checkEli5Html(valid.replace('<svg ', '<svg style="fill:url(https://example.com/a.png)" ')));
  assert.ok(checkEli5Html(valid.replace('<svg ', '<svg style="fill:url(data:image/png;base64,AAAA)" ')));
  assert.ok(checkEli5Html(valid.replace('<svg ', '<svg style="fill:url(')));
  assert.ok(checkEli5Html('<html><body>片段</body></html>'));
  assert.ok(checkEli5Html('<!DOCTYPE html><html><head></head><body><svg></svg></body></html>'));
  assert.ok(checkEli5Html(valid, true));
  assert.ok(checkEli5Html(valid.replace('</body>', '<script>alert(1)</script></body>')));
  assert.ok(checkEli5Html(valid.replace('</body>', '<img src="https://example.com/a.png"></body>')));
  assert.ok(checkEli5Html(valid.replace('</head>', '<meta http-equiv="refresh" content="0;url=https://example.com"></head>')));
  const exercise = JSON.stringify(Array.from({ length: 3 }, (_, i) => ({ question: `问题${i}`, difficulty: ['持平', '进阶', '培优'][i], answer: '答案', analysis: '解析' })));
  const replies = ['bad', valid, 'bad json', exercise];
  const states = [];
  await runEli5Pipeline({ grade: 'junior', topic: '数学', images: [], ctx: {}, signal: new AbortController().signal, call: async () => replies.shift(), update: state => states.push(state) });
  assert.equal(states[0].stage, 'practicing');
  assert.equal(states[1].stage, 'done');
  assert.equal(states[1].promptVersion, '2.4');
  assert.equal(states[1].practices.length, 3);
  assert.equal(replies.length, 0);
  const wrongOrder = JSON.stringify(['持平', '培优', '进阶'].map(difficulty => ({ question: '问题', difficulty, answer: '答案', analysis: '解析' })));
  const orderedStates = [];
  let orderCalls = 0;
  await runEli5Pipeline({ grade: 'junior', topic: '数学', images: [], ctx: {}, signal: new AbortController().signal, call: async () => [valid, wrongOrder, exercise][orderCalls++], update: state => orderedStates.push(state) });
  assert.equal(orderCalls, 3);
  assert.deepEqual(orderedStates.at(-1).practices.map(item => item.difficulty), ['持平', '进阶', '培优']);
  const fourLevels = JSON.stringify(['持平', '持平', '进阶', '培优'].map(difficulty => ({ question: '问题', difficulty, answer: '答案', analysis: '解析' })));
  const fourStates = [];
  let fourCalls = 0;
  await runEli5Pipeline({ grade: 'junior', topic: '数学', images: [], ctx: {}, signal: new AbortController().signal, call: async () => [valid, fourLevels][fourCalls++], update: state => fourStates.push(state) });
  assert.equal(fourCalls, 2);
  assert.equal(fourStates.at(-1).practices.length, 4);
  const missingMiddle = JSON.stringify(['持平', '持平', '培优'].map(difficulty => ({ question: '问题', difficulty, answer: '答案', analysis: '解析' })));
  const missingStates = [];
  let missingCalls = 0;
  await runEli5Pipeline({ grade: 'junior', topic: '数学', images: [], ctx: {}, signal: new AbortController().signal, call: async () => missingCalls++ === 0 ? valid : missingMiddle, update: state => missingStates.push(state) });
  assert.equal(missingStates.at(-1).stage, 'error');
  assert.equal(missingStates.at(-1).html, valid);
  assert.equal(missingStates.at(-1).retryPractice, true);
  const oversizedPractice = JSON.stringify(['持平', '进阶', '培优'].map((difficulty, index) => ({ question: index === 1 ? 'x'.repeat(4001) : '问题', difficulty, answer: '答案', analysis: '解析' })));
  const oversizedStates = [];
  let oversizedCalls = 0;
  await runEli5Pipeline({ grade: 'junior', topic: '数学', images: [], ctx: {}, signal: new AbortController().signal, call: async () => oversizedCalls++ === 0 ? valid : oversizedPractice, update: state => oversizedStates.push(state) });
  assert.equal(oversizedCalls, 3);
  assert.equal(oversizedStates.at(-1).stage, 'error');
  assert.equal(oversizedStates.at(-1).retryPractice, true);
  assert.equal(oversizedStates.at(-1).practices, undefined);
  const figurePractice = JSON.stringify(['持平', '进阶', '培优'].map((difficulty, index) => ({ question: index === 0 ? '如图，求这个图形的面积。' : '问题', difficulty, answer: '答案', analysis: '解析' })));
  const figureStates = [];
  let figureCalls = 0;
  await runEli5Pipeline({ grade: 'junior', topic: '几何', images: [], ctx: {}, signal: new AbortController().signal, call: async () => figureCalls++ === 0 ? valid : figurePractice, update: state => figureStates.push(state) });
  assert.equal(figureCalls, 3);
  assert.equal(figureStates.at(-1).stage, 'error');
  assert.equal(figureStates.at(-1).retryPractice, true);
  assert.equal(figureStates.at(-1).practices, undefined);
  const picture = 'data:image/png;base64,dGVzdA==';
  const messages = [];
  const pictureStates = [];
  await runEli5Pipeline({ grade: 'junior', topic: '请解释图中过程', images: [picture], ctx: {}, signal: new AbortController().signal, call: async items => { messages.push(items); return messages.length === 1 ? valid : exercise; }, update: state => pictureStates.push(state) });
  assert.equal(pictureStates.at(-1).stage, 'done');
  assert.equal(pictureStates.at(-1).sourceImageCount, 1);
  assert.ok(!messages[0][0].content.includes('请解释图中过程'));
  for (const call of messages) {
    const user = call.find(message => message.role === 'user');
    assert.ok(Array.isArray(user.content));
    assert.equal(user.content.filter(part => part.type === 'image_url').length, 1);
    assert.equal(user.content.find(part => part.type === 'image_url').image_url.url, picture);
    assert.ok(user.content.find(part => part.type === 'text').text.includes('请解释图中过程'));
  }
  const textOnlyHtml = '<!DOCTYPE html><html><head><style>.decoration{border:20px solid red}</style></head><body><h2>先看温度</h2><p>热量从温度较高处传向温度较低处。</p><ul><li>再观察变化。</li></ul><p>记住 &quot;方向&quot; 与 &#x26; 符号。</p></body></html>';
  const textOnlyStates = [];
  let textOnlyCalls = 0;
  await runEli5Pipeline({ grade: 'senior', topic: '解释热传导', images: [], textOnly: true, ctx: {}, signal: new AbortController().signal, call: async items => { textOnlyCalls++; if (textOnlyCalls === 1) { assert.match(items[0].content, /不绘制图形/); return valid; } return textOnlyCalls === 2 ? textOnlyHtml : exercise; }, update: state => textOnlyStates.push(state) });
  assert.equal(textOnlyCalls, 3);
  assert.equal(textOnlyStates.at(-1).stage, 'done');
  assert.match(textOnlyStates.at(-1).html, /热量从温度较高处/);
  assert.match(textOnlyStates.at(-1).html, /<p>先看温度<\/p><p>热量从温度较高处传向温度较低处。<\/p><p>再观察变化。<\/p>/);
  assert.match(textOnlyStates.at(-1).html, /记住 &quot;方向&quot; 与 &amp; 符号/);
  assert.doesNotMatch(textOnlyStates.at(-1).html, /<svg|decoration|border:20px/);
  const fallbackStates = [];
  let fallbackCalls = 0;
  await runEli5UnverifiedFallback({
    grade: 'senior', topic: '斜面上的物块', images: [], ctx: {}, signal: new AbortController().signal,
    call: async items => {
      fallbackCalls++;
      if (fallbackCalls <= 2) assert.match(items[0].content, /不绘制图形/);
      return fallbackCalls === 1 ? valid : fallbackCalls === 2 ? textOnlyHtml : exercise;
    },
    update: state => fallbackStates.push(state),
  });
  assert.equal(fallbackCalls, 3);
  assert.equal(fallbackStates.at(-1).stage, 'done');
  assert.equal(fallbackStates.at(-1).physicsUnverified, true);
  assert.equal(fallbackStates.at(-1).physicsTextOnly, true);
  assert.match(fallbackStates.at(-1).html, /热量从温度较高处/);
  assert.doesNotMatch(fallbackStates.at(-1).html, /<svg/);
  assert.ok(fallbackStates.every(state => state.physicsUnverified === true && state.physicsTextOnly === true));
  const imagePractice = JSON.stringify(Array.from({ length: 3 }, (_, i) => ({ question: `问题${i} ![图](https://example.com/a.png)`, difficulty: ['持平', '进阶', '培优'][i], answer: '答案', analysis: '解析' })));
  const blockedStates = [];
  let blockedCalls = 0;
  await runEli5Pipeline({ grade: 'senior', topic: '解释热传导', images: [], textOnly: true, ctx: {}, signal: new AbortController().signal, call: async items => { blockedCalls++; if (blockedCalls > 1) assert.match(items[0].content, /只用文字/); return blockedCalls === 1 ? textOnlyHtml : imagePractice; }, update: state => blockedStates.push(state) });
  assert.equal(blockedCalls, 3);
  assert.equal(blockedStates.at(-1).stage, 'error');
  assert.equal(blockedStates.at(-1).retryPractice, true);
  assert.equal(blockedStates.at(-1).practices, undefined);
  const textRetryStates = [];
  let textRetryCalls = 0;
  await runEli5Practice({ grade: 'senior', topic: '解释热传导', images: [], textOnly: true, ctx: {}, signal: new AbortController().signal, initial: blockedStates.at(-1), call: async items => { textRetryCalls++; assert.match(items[0].content, /只用文字/); return textRetryCalls === 1 ? imagePractice : exercise; }, update: state => textRetryStates.push(state) });
  assert.equal(textRetryCalls, 2);
  assert.equal(textRetryStates.at(-1).stage, 'done');
  assert.equal(textRetryStates.at(-1).practices.length, 3);
  const clarificationHtml = valid.replace('<head></head>', `<head><meta content='needs-clarification' name='eli5-input-status'></head>`).replace('这是一幅图', '图片中的数字看不清，请补充数字。');
  const clarificationStates = [];
  let clarificationCalls = 0;
  await runEli5Pipeline({ grade: 'junior', topic: '请解释图片', images: [picture], ctx: {}, signal: new AbortController().signal, call: async () => { clarificationCalls++; return clarificationHtml; }, update: state => clarificationStates.push(state) });
  assert.equal(clarificationCalls, 1);
  assert.equal(clarificationStates.at(-1).stage, 'clarification');
  assert.equal(clarificationStates.at(-1).html, clarificationHtml);
  assert.equal(clarificationStates.at(-1).practices, undefined);
  const partialStates = [];
  let partialCalls = 0;
  await runEli5Pipeline({ grade: 'senior', topic: '化学反应', images: [], ctx: {}, signal: new AbortController().signal, call: async () => { if (++partialCalls === 1) return valid; throw new Error('连接失败'); }, update: state => partialStates.push(state) });
  assert.equal(partialStates.at(-1).stage, 'error');
  assert.equal(partialStates.at(-1).html, valid);
  assert.match(partialStates.at(-1).error, /讲解已生成.*练习生成失败.*连接失败/);
  assert.equal(partialStates.at(-1).retryPractice, true);
  const retryStates = [];
  let retryCalls = 0;
  await runEli5Practice({ grade: 'senior', topic: '化学反应', images: [picture], ctx: {}, signal: new AbortController().signal, initial: partialStates.at(-1), call: async items => { retryCalls++; assert.equal(items[1].content[1].image_url.url, picture); return exercise; }, update: state => retryStates.push(state) });
  assert.equal(retryCalls, 1);
  assert.equal(retryStates.at(-1).stage, 'done');
  assert.equal(retryStates.at(-1).html, valid);
  assert.equal(retryStates.at(-1).retryPractice, false);
  assert.equal(retryStates.at(-1).practices.length, 3);
  for (const [grade, topic] of [['primary', '植物怎样长大'], ['junior', '为什么会有四季'], ['senior', '电路中的电流']]) {
    const seen = [];
    const outputs = [];
    await runEli5Pipeline({ grade, topic, images: [], ctx: {}, signal: new AbortController().signal, call: async items => { seen.push(items); return seen.length === 1 ? valid : exercise; }, update: state => outputs.push(state) });
    assert.equal(outputs.at(-1).stage, 'done');
    assert.ok(seen[0].find(message => message.role === 'user').content.includes(topic));
    assert.ok(seen[1].find(message => message.role === 'user').content.includes(topic));
  }
  const mismatchMessages = [];
  await runEli5Pipeline({ grade: 'junior', topic: '二次函数', images: [], ctx: { gradeLevel: '高三' }, signal: new AbortController().signal, call: async items => { mismatchMessages.push(items); return mismatchMessages.length === 1 ? valid : exercise; }, update() {} });
  assert.doesNotMatch(mismatchMessages[0][0].content, /高三（初中）/);
  assert.match(mismatchMessages[0][0].content, /二次函数属于义务教育内容/);
  const invalidStates = [];
  await runEli5Pipeline({ grade: 'junior', topic: '数学', images: [], ctx: {}, signal: new AbortController().signal, call: async () => 'bad', update: state => invalidStates.push(state) });
  assert.equal(invalidStates[0].stage, 'error');
  assert.equal(invalidStates[0].html, undefined);
  assert.equal(invalidStates[0].retryLesson, true);
  const controller = new AbortController();
  const cancelledStates = [];
  await assert.rejects(runEli5Pipeline({ grade: 'junior', topic: '数学', images: [], ctx: {}, signal: controller.signal, call: async () => { controller.abort(); return valid; }, update: state => cancelledStates.push(state) }));
  assert.equal(cancelledStates.length, 0);
  process.stdout.write('ELI5 pipeline checks passed\n');
} finally {
  await unlink(join(dir, "pipeline.mjs")).catch(() => {});
  await rmdir(dir);
}
