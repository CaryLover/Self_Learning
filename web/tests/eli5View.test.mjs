import { build } from "esbuild";
import { pathToFileURL } from "node:url";
import { mkdtemp, unlink, rmdir, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import assert from "node:assert/strict";

const dir = await mkdtemp(join(tmpdir(), "eli5-view-"));
const outfile = join(dir, "view.cjs");
try {
  const bundle = await build({ stdin: { contents: `export { createElement } from 'react'; export { renderToStaticMarkup } from 'react-dom/server'; export { Eli5View } from './src/components/Eli5View.tsx'; export { recoverSession } from './src/lib/recoverSession.ts'; export { recoverLessonImages } from './src/lib/sessionImages.ts';`, resolveDir: process.cwd(), loader: "tsx" }, bundle: true, platform: "node", format: "cjs", write: false, outfile, loader: { ".css": "empty" } });
  await writeFile(outfile, bundle.outputFiles[0].contents);
  const { createElement, renderToStaticMarkup, Eli5View, recoverSession, recoverLessonImages } = (await import(pathToFileURL(outfile).href)).default;
  const html = '<!DOCTYPE html><html><body><p>已生成的讲解</p></body></html>';
  const render = (eli5, busy = false, physicsRetryEnabled = false) => renderToStaticMarkup(createElement(Eli5View, { eli5, busy, physicsRetryEnabled, onRetryLesson() {}, onRetryPractice() {}, onRetryPhysicsExplanation() {}, onSkipPhysicsExplanation() {}, onContinueUnverified() {} }));
  const failed = render({ stage: 'error', html, retryPractice: true, error: '练习生成失败' });
  assert.match(failed, /重新生成练习/);
  assert.match(failed, /练习生成失败/);
  assert.match(failed, /已生成的讲解/);
  assert.match(failed, /sandbox=""/);
  assert.match(failed, /Content-Security-Policy/);
  assert.match(failed, /default-src &#x27;none&#x27;/);
  assert.match(render({ stage: 'error', html, retryPractice: true, error: '失败' }, true), /disabled=""/);
  assert.doesNotMatch(render({ stage: 'error', error: '讲解失败' }), /重新生成练习/);
  assert.match(render({ stage: 'clarification', html }), /请根据讲解中的提示补充信息/);
  assert.doesNotMatch(render({ stage: 'clarification', html }), /巩固练习/);
  assert.match(render({ stage: 'physics_explaining', html }), /物理图已生成，正在组织讲解/);
  assert.match(render({ stage: 'done', html, physicsUnverified: true }), /未使用物理工具核验/);
  assert.match(render({ stage: 'done', html, physicsUnverified: true, physicsTextOnly: true }), /模型文字讲解/);
  const unsafePractice = [{ question: '[链接](//example.com)', answer: 'www.example.com', analysis: '![图](//example.com/a.png)', difficulty: '持平' }];
  const textOnlyPractice = render({ stage: 'done', html, physicsTextOnly: true, practices: unsafePractice });
  assert.doesNotMatch(textOnlyPractice, /<(?:a|img)\b/);
  assert.match(render({ stage: 'error', html, retryPhysicsExplanation: true, error: '失败' }, false, true), /重新生成物理讲解/);
  assert.match(render({ stage: 'error', html, retryPhysicsExplanation: true, error: '失败' }, false, true), /保留物理图和练习/);
  assert.doesNotMatch(render({ stage: 'error', html, retryPhysicsExplanation: true, error: '失败' }), /保留物理图和练习/);
  assert.doesNotMatch(render({ stage: 'error', html, retryPhysicsExplanation: true, error: '失败' }), /重新生成物理讲解/);
  assert.match(render({ stage: 'error', html, retryPhysicsExplanation: true, error: '失败' }), /当前版本未启用物理预览/);
  const reviewable = render({ stage: 'error', error: '物理工具无法自动核对这道题：条件和依据不完整', retryLesson: true, unverifiedFallback: true });
  assert.match(reviewable, /重新生成讲解/);
  assert.match(reviewable, /改用普通讲解/);
  assert.match(reviewable, /不经过物理工具核验/);
  assert.doesNotMatch(render({ stage: 'error', error: '失败', retryLesson: true }), /改用普通讲解/);
  const reviewableBusy = render({ stage: 'error', error: '物理工具无法自动核对', unverifiedFallback: true }, true);
  assert.match(reviewableBusy, /改用普通讲解（不做物理核验）/);
  assert.match(reviewableBusy, /disabled=""/);
  const session = eli5 => ({ id: 'session', eli5, messages: [], turns: [] });
  const practice = recoverSession(session({ stage: 'practicing', topic: '主题', html, physicsTextOnly: true })).eli5;
  assert.match(render(practice), /重新生成练习/);
  assert.match(render(practice), /已生成的讲解/);
  assert.equal(practice.physicsTextOnly, true);
  const physics = recoverSession(session({ stage: 'physics_explaining', topic: '主题', html, physicsPreview: {}, pendingPhysicsPractices: [] })).eli5;
  assert.match(render(physics, false, true), /重新生成物理讲解/);
  assert.match(render(physics, false, true), /已生成的讲解/);
  assert.doesNotMatch(render(recoverSession(session({ stage: 'physics_explaining', html })).eli5, false, true), /重新生成物理讲解/);
  assert.match(render(recoverSession(session({ stage: 'physics_explaining', topic: '主题' })).eli5, false, true), /重新生成讲解/);
  assert.match(render(recoverSession(session({ stage: 'practicing', topic: '主题' })).eli5), /重新生成讲解/);
  assert.match(render(recoverSession(session({ stage: 'explaining', topic: '主题' })).eli5), /重新生成讲解/);
  const completed = session({ stage: 'done', html });
  assert.equal(recoverSession(completed), completed);
  const reviewSession = recoverSession(session({ stage: 'error', topic: '主题', retryLesson: true, unverifiedFallback: true, error: '复核' })).eli5;
  assert.equal(reviewSession.unverifiedFallback, true);
  assert.match(render(reviewSession), /改用普通讲解/);
  const picture = 'data:image/png;base64,dGVzdA==';
  const savedPicture = { messages: [{ role: 'user', images: [picture] }], eli5: { sourceImageCount: 1 } };
  assert.deepEqual(recoverLessonImages(savedPicture), [picture]);
  assert.equal(recoverLessonImages({ ...savedPicture, messages: [{ role: 'user' }] }), null);
  assert.equal(recoverLessonImages({ ...savedPicture, messages: [{ role: 'user', images: [null] }] }), null);
  assert.deepEqual(recoverLessonImages({ messages: [{ role: 'user', images: [picture] }], eli5: {} }), [picture]);
  assert.equal(recoverLessonImages({ messages: [{ role: 'user', content: '请讲解这张图片里的题目。' }], eli5: {} }), null);
  console.log('ELI5 view checks passed');
} finally {
  await unlink(outfile).catch(() => {});
  await rmdir(dir);
}
